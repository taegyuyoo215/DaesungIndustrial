-- ─────────────────────────────────────────────
-- 1. fft_spectra 테이블
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS fft_spectra (
    id              SERIAL PRIMARY KEY,
    motor_id        INTEGER     NOT NULL REFERENCES motors(id),
    sensor_id       INTEGER     NOT NULL REFERENCES sensors(id),
    measured_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    axis            TEXT        NOT NULL CHECK (axis IN ('x','y','z')),
    fmax_hz         NUMERIC(8,2) NOT NULL DEFAULT 1000,
    resolution_hz   NUMERIC(8,4) NOT NULL DEFAULT 10.0,
    rpm_measured    NUMERIC(8,2),
    -- 주파수 빈(Hz) 배열과 진폭(mm/s) 배열 (길이 동일)
    freq_bins       NUMERIC[]   NOT NULL,
    amp_bins        NUMERIC[]   NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_fft_spectra_motor_time
    ON fft_spectra (motor_id, measured_at DESC);

CREATE INDEX IF NOT EXISTS idx_fft_spectra_sensor_time
    ON fft_spectra (sensor_id, measured_at DESC);

